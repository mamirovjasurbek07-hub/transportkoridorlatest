def _flag(alpha2: str) -> str:
    if len(alpha2) != 2 or not alpha2.isalpha():
        return "🌐"
    return "".join(chr(127397 + ord(letter)) for letter in alpha2.upper())


def _country(row: str) -> dict:
    numeric, alpha2, alpha3, name, latitude, longitude = row.split("|")
    return {
        "numeric": numeric,
        "alpha2": alpha2,
        "alpha3": alpha3,
        "name": name,
        "flag": _flag(alpha2),
        "latitude": float(latitude) if latitude else None,
        "longitude": float(longitude) if longitude else None,
    }


