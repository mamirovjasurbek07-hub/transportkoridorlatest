async def seed_all(db: AsyncSession) -> None:
    # This application currently manages the bootstrap administrator through
    # Render environment variables. Keep the single existing admin in sync so
    # changing those variables can recover access without editing password
    # hashes directly in Supabase.
    email = settings.admin_initial_email.strip().lower()
    user = await db.scalar(select(User).where(func.lower(User.email) == email))
    admin_action = "verified"
    if user is None:
        admins = (await db.scalars(select(User).where(User.role == "ADMIN").order_by(User.created_at))).all()
        if len(admins) == 1:
            user = admins[0]
            user.email = email
            admin_action = "email_updated"
        else:
            user = User(email=email, password_hash=hash_password(settings.admin_initial_password), role="ADMIN")
            db.add(user)
            admin_action = "created"
    else:
        user.email = email
    user.role = "ADMIN"
    user.is_active = True
    try:
        password_matches = verify_password(settings.admin_initial_password, user.password_hash)
    except Exception:
        password_matches = False
    if not password_matches:
        user.password_hash = hash_password(settings.admin_initial_password)
        admin_action = f"{admin_action}+password_updated"
    await logger.ainfo("admin_credentials_synchronized", action=admin_action)
    existing_posts = {post.post_code: post for post in (await db.scalars(select(CustomsPost))).all()}
    for code, name, post_type, country in POSTS:
        post = existing_posts.get(code)
        lat, lng = COORDINATES.get(code, (None, None))
        is_new = post is None
        if is_new:
            post = CustomsPost(post_code=code)
            db.add(post)
            post.is_active = True
        post.post_name = _official_post_name(code, name, post_type)
        post.post_type = post_type
        post.post_category = POST_CATEGORIES.get(code, "UNASSIGNED")
        post.neighbor_country_code = country
        if lat is not None and (is_new or post.latitude is None or post.longitude is None):
            post.latitude = lat
            post.longitude = lng
            post.location_verified = True
            post.location = ST_SetSRID(ST_MakePoint(lng, lat), 4326)
    await db.flush()
    existing_gateways = set((await db.scalars(select(CountryGateway.name))).all())
    for country, name, gateway_type, lat, lng, neighbor, notes in GATEWAYS:
        if name in existing_gateways:
            continue
        gateway = CountryGateway(country_code=country, name=name, gateway_type=gateway_type, latitude=lat, longitude=lng,
            neighbor_country_code=neighbor, verified=True, is_active=True, notes=notes)
        gateway.location = ST_SetSRID(ST_MakePoint(lng, lat), 4326)
        db.add(gateway)
    await db.flush()
    # Seed code must never trigger relationship lazy-loading in an async
    # session. Waypoints are replaced explicitly below.
    existing_corridors = {
        corridor.code: corridor
        for corridor in (await db.scalars(select(Corridor).options(noload(Corridor.waypoints)))).all()
    }
    current_route_codes = {route["code"] for route in ROUTES}
    for code, corridor in existing_corridors.items():
        if code not in current_route_codes and corridor.geometry_source in LEGACY_SEED_GEOMETRY_SOURCES | {PENDING_SEED_GEOMETRY_SOURCE}:
            corridor.is_active = False
            corridor.status = "INACTIVE"
    for priority, route in enumerate(ROUTES, start=1):
        corridor = existing_corridors.get(route["code"])
        if corridor is not None:
            if corridor.geometry_source == PENDING_SEED_GEOMETRY_SOURCE:
                continue
            if corridor.geometry_source not in LEGACY_SEED_GEOMETRY_SOURCES:
                continue
        if corridor is None:
            corridor = Corridor(code=route["code"])
            db.add(corridor)
        corridor.name = route["name"]
        corridor.origin_country_code = route["origin"]
        corridor.destination_country_code = route["destination"]
        corridor.entry_post_code = route["entry"]
        corridor.exit_post_code = route["exit"]
        corridor.status = "REVIEW"
        corridor.color = route["color"]
        corridor.geometry_source = PENDING_SEED_GEOMETRY_SOURCE
        corridor.routing_provider = "pending"
        corridor.geometry = None
        corridor.distance_meters = None
        corridor.duration_seconds = None
        corridor.route_needs_review = True
        corridor.priority = priority
        corridor.is_active = True
        await db.flush()
        await db.execute(
            delete(CorridorWaypoint)
            .where(CorridorWaypoint.corridor_id == corridor.id)
            .execution_options(synchronize_session=False)
        )
        for seq, waypoint in enumerate(route["waypoints"]):
            coord = waypoint["coord"]
            wp = CorridorWaypoint(corridor_id=corridor.id, sequence_no=seq, waypoint_type=waypoint["type"], latitude=coord[1], longitude=coord[0],
                post_code=waypoint.get("post_code"), label=waypoint.get("label"))
            wp.location = ST_SetSRID(ST_MakePoint(coord[0], coord[1]), 4326)
            db.add(wp)
    if settings.enable_demo_seed:
        await seed_demo_declarations(db)
        await seed_demo_post_metrics(db)
    await db.commit()


async def rebuild_pending_seed_routes(session_factory) -> None:
    """Replace every legacy hand-drawn demo line with an actual router result."""
    async with session_factory() as db:
        corridor_ids = list((await db.scalars(
            select(Corridor.id).where(
                Corridor.is_active.is_(True),
                Corridor.geometry_source == PENDING_SEED_GEOMETRY_SOURCE,
            ).order_by(Corridor.priority, Corridor.code)
        )).all())
    if not corridor_ids:
        return
    await logger.ainfo("seed_route_rebuild_started", total=len(corridor_ids), provider=RoutingService._provider())
    rebuilt = failed = 0
    for corridor_id in corridor_ids:
        async with session_factory() as db:
            corridor = await db.scalar(
                select(Corridor).options(selectinload(Corridor.waypoints)).where(Corridor.id == corridor_id)
            )
            if corridor is None or corridor.geometry_source != PENDING_SEED_GEOMETRY_SOURCE:
                continue
            ordered = sorted(corridor.waypoints, key=lambda point: point.sequence_no)
            waypoint_data = [{"latitude": point.latitude, "longitude": point.longitude} for point in ordered]
            try:
                result = await RoutingService(db).route(waypoint_data, profile=corridor.routing_profile)
                if result.available and result.geometry:
                    corridor.geometry = ST_GeomFromGeoJSON(json.dumps(result.geometry))
                    corridor.geometry_hash = hashlib.sha256(json.dumps(result.geometry, sort_keys=True).encode()).hexdigest()
                    corridor.distance_meters = result.distance_meters
                    corridor.duration_seconds = result.duration_seconds
                    corridor.geometry_source = f"{result.provider}-router"
                    corridor.routing_provider = result.provider
                    corridor.route_needs_review = False
                    corridor.status = "ACTIVE"
                    rebuilt += 1
                else:
                    corridor.geometry = None
                    corridor.distance_meters = None
                    corridor.duration_seconds = None
                    corridor.route_needs_review = True
                    corridor.status = "REVIEW"
                    failed += 1
                    await logger.awarning("seed_route_rebuild_failed", code=corridor.code, message=result.message)
                await db.commit()
                if not result.cached:
                    await asyncio.sleep(1.05)
            except Exception as exc:
                await db.rollback()
                failed += 1
                await logger.aerror("seed_route_rebuild_error", code=corridor.code, error=type(exc).__name__)
                await asyncio.sleep(1.05)
    await logger.ainfo("seed_route_rebuild_finished", total=len(corridor_ids), rebuilt=rebuilt, failed=failed)
