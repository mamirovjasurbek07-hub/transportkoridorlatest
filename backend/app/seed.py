def _internationalize(route: dict) -> None:
    internal_coords = route["coords"]
    origin_leg = POST_TO_GATEWAY.get((route["entry"], route["origin"])) if route["origin"] != "UZ" else None
    destination_leg = POST_TO_GATEWAY.get((route["exit"], route["destination"])) if route["destination"] != "UZ" else None
    coords = internal_coords
    if origin_leg:
        coords = _join(list(reversed(origin_leg)), coords)
    if destination_leg:
        coords = _join(coords, destination_leg)
    waypoint_specs: list[dict] = []
    if origin_leg:
        waypoint_specs.append({"coord": origin_leg[-1], "type": "ORIGIN_GATEWAY", "label": f"{route['origin']} logistika gateway"})
    waypoint_specs.append({"coord": internal_coords[0], "type": "ENTRY_POST", "post_code": route["entry"]})
    includes_tashkent = any(abs(point[0] - TASHKENT_JUNCTION[0]) < 0.000001 and abs(point[1] - TASHKENT_JUNCTION[1]) < 0.000001 for point in internal_coords)
    if includes_tashkent and internal_coords[0] != TASHKENT_JUNCTION and internal_coords[-1] != TASHKENT_JUNCTION:
        waypoint_specs.append({"coord": TASHKENT_JUNCTION, "type": "VIA", "label": "Toshkent tranzit tuguni"})
    waypoint_specs.append({"coord": internal_coords[-1], "type": "EXIT_POST", "post_code": route["exit"]})
    if destination_leg:
        waypoint_specs.append({"coord": destination_leg[-1], "type": "DESTINATION_GATEWAY", "label": f"{route['destination']} logistika gateway"})
    route["coords"] = coords
    route["waypoints"] = waypoint_specs
    route["distance"] = _road_length(coords)
    route["duration"] = round(route["distance"] / 15)


